function readLocale() {
  try {
    return localStorage.getItem(STORAGE_KEY) === 'en' ? 'en' : DEFAULT_LOCALE
  } catch {
    return DEFAULT_LOCALE
  }
}

function interpolate(value, params = {}) {
  return value.replace(/\{(\w+)\}/g, (_, key) => params[key] == null ? '' : String(params[key]))
}

export function translate(key, locale = DEFAULT_LOCALE, params = {}) {
  const value = locale === 'en' ? (EN[key] || key) : key
  return interpolate(value, params)
}

const LocaleContext = createContext(null)

export function LocaleProvider({ children }) {
  const [locale, setLocale] = useState(readLocale)
  useEffect(() => {
    try { localStorage.setItem(STORAGE_KEY, locale) } catch {}
    document.documentElement.lang = locale === 'en' ? 'en' : 'zh-CN'
    document.title = locale === 'en' ? 'Style Shelf · Style Workbench' : 'Style Shelf · 风格仓库'
  }, [locale])
  const value = useMemo(() => ({
    locale,
    setLocale,
    t: (key, params) => translate(key, locale, params),
    toggleLocale: () => setLocale((current) => current === 'en' ? 'zh-CN' : 'en'),
  }), [locale])
  return createElement(LocaleContext.Provider, { value }, children)
}

export function useI18n() {
  const context = useContext(LocaleContext)
  if (!context) throw new Error('useI18n must be used inside LocaleProvider')
  return context
}

